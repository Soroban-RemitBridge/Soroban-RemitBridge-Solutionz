//! Registry implementation.
//!
//! Public entry points are thin: they perform authentication, then delegate to
//! private free functions that take `&Env`. Keeping the logic out of the trait
//! impl means it can be unit-tested directly and composed (e.g. `is_authorized`
//! is reused by `is_authorized_for_corridor`) without re-entering the public
//! ABI and its auth checks.

use soroban_sdk::{contractimpl, token, Address, Env, Symbol, Vec};

use crate::errors::AgentRegistryError;
use crate::events;
use crate::storage;
use crate::types::{Agent, AgentStatus, RegionConfig, RegistryStats};
// `AgentRegistryArgs` and `AgentRegistryClient` are generated by `#[contract]`
// in the crate root; the `#[contractimpl]` macro below refers to them, so they
// have to be in scope inside this module too.
use crate::{AgentRegistry, AgentRegistryArgs, AgentRegistryClient, AgentRegistryInterface};

/* ------------------------------------------------------------------ */
/* internal helpers                                                    */
/* ------------------------------------------------------------------ */

fn require_admin(env: &Env) -> Result<Address, AgentRegistryError> {
    let admin = storage::get_admin(env)?;
    admin.require_auth();
    Ok(admin)
}

fn load_agent(env: &Env, agent: &Address) -> Result<Agent, AgentRegistryError> {
    storage::get_agent(env, agent).ok_or(AgentRegistryError::AgentNotRegistered)
}

fn load_region(env: &Env, region_id: &Symbol) -> Result<RegionConfig, AgentRegistryError> {
    storage::get_region(env, region_id).ok_or(AgentRegistryError::UnknownRegion)
}

fn money_out(
    env: &Env,
    token: &Address,
    to: &Address,
    amount: i128,
) -> Result<(), AgentRegistryError> {
    if amount <= 0 {
        return Err(AgentRegistryError::InvalidAmount);
    }
    token::Client::new(env, token).transfer(&env.current_contract_address(), to, &amount);
    Ok(())
}

/// Count agents currently allowed to settle in a region. Used to enforce the
/// per-region cap at authorization time.
fn count_authorized(env: &Env, region_id: &Symbol) -> u32 {
    let mut count = 0u32;
    for address in storage::region_agents(env, region_id).iter() {
        if let Some(record) = storage::get_agent(env, &address) {
            if record.status == AgentStatus::Authorized {
                count = count.saturating_add(1);
            }
        }
    }
    count
}

fn is_authorized_in(env: &Env, agent: &Address, region_id: &Symbol) -> bool {
    match storage::get_agent(env, agent) {
        Some(record) => {
            let region_active = storage::get_region(env, region_id).is_some_and(|c| c.active);
            record.status.can_settle() && region_active && &record.region_id == region_id
        }
        None => false,
    }
}

/// Apply a lifecycle transition, keeping the `authorized_agents` counter and the
/// event stream consistent. Returns the state we came from.
fn apply_transition(
    env: &Env,
    record: &mut Agent,
    to: AgentStatus,
    reason: &Symbol,
) -> AgentStatus {
    let from = record.status;
    record.status = to;
    record.updated_at = env.ledger().timestamp();
    storage::set_agent(env, record);

    let mut stats = storage::get_stats(env);
    if from == AgentStatus::Authorized && to != AgentStatus::Authorized {
        stats.authorized_agents = stats.authorized_agents.saturating_sub(1);
    } else if from != AgentStatus::Authorized && to == AgentStatus::Authorized {
        stats.authorized_agents = stats.authorized_agents.saturating_add(1);
    }
    storage::set_stats(env, &stats);

    events::agent_status_changed(env, &record.address, &record.region_id, from, to, reason);
    from
}

