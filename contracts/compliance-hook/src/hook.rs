//! Compliance hook implementation.
//!
//! The decision logic lives in `evaluate`, a pure-ish function that reads state
//! and returns either the resolved tiers or the exact rule that refused the
//! transfer. Both the boolean gate and the UI-facing explanation are thin
//! projections of it, which is what keeps "what the app said" and "what the
//! contract enforced" from diverging.

use soroban_sdk::{contractimpl, symbol_short, Address, BytesN, Env, Symbol, Vec};

use crate::errors::ComplianceError;
use crate::events;
use crate::storage;
use crate::types::{Attestation, ComplianceStats, KycTier, TierThresholds, TransferDecision};
// Generated by `#[contract]` in the crate root; the `#[contractimpl]` macro
// below refers to them from inside this module.
use crate::{ComplianceHook, ComplianceHookArgs, ComplianceHookClient, ComplianceHookInterface};

/// Resolved outcome of a successful evaluation.
struct Evaluation {
    required_tier: KycTier,
    held_tier: KycTier,
    remaining_daily: i128,
    /// The sender's volume for this day *including* this transfer.
    ///
    /// Carried out of the evaluation so the write path does not have to read the
    /// same bucket a second time: the ceiling check and the increment are then
    /// guaranteed to be reading one value rather than two.
    daily_total_after: i128,
}

fn require_admin(env: &Env) -> Result<Address, ComplianceError> {
    let admin = storage::get_admin(env)?;
    admin.require_auth();
    Ok(admin)
}

/// Machine-readable tag for a refusal, so the same vocabulary is used in events,
/// API responses and the admin console.
fn reason_tag(error: ComplianceError) -> Symbol {
    match error {
        ComplianceError::NotInitialized => symbol_short!("no_init"),
        ComplianceError::AlreadyInitialized => symbol_short!("inited"),
        ComplianceError::Unauthorized => symbol_short!("unauth"),
        ComplianceError::NotAnAttester => symbol_short!("no_attest"),
        ComplianceError::NotEscrow => symbol_short!("not_escr"),
        ComplianceError::InvalidAmount => symbol_short!("bad_amt"),
        ComplianceError::UnknownCorridor => symbol_short!("no_corr"),
        ComplianceError::InvalidThresholds => symbol_short!("bad_tier"),
        ComplianceError::TransfersPaused => symbol_short!("paused"),
        ComplianceError::AttestationMissing => symbol_short!("kyc_need"),
        ComplianceError::AttestationExpired => symbol_short!("kyc_exp"),
        ComplianceError::AttestationRevoked => symbol_short!("kyc_rev"),
        ComplianceError::TierTooLow => symbol_short!("tier_low"),
        ComplianceError::DailyLimitExceeded => symbol_short!("daily_cap"),
        ComplianceError::InvalidExpiry => symbol_short!("exp_bad"),
        ComplianceError::Overflow => symbol_short!("overflow"),
        ComplianceError::EscrowNotSet => symbol_short!("no_escr"),
    }
}

/// The single source of truth for "may this transfer proceed?".
fn evaluate(
    env: &Env,
    sender: &Address,
    amount: i128,
    corridor_id: &Symbol,
) -> Result<Evaluation, ComplianceError> {
    if storage::is_paused(env) {
        return Err(ComplianceError::TransfersPaused);
    }
    if amount <= 0 {
        return Err(ComplianceError::InvalidAmount);
    }

    let thresholds =
        storage::get_thresholds(env, corridor_id).ok_or(ComplianceError::UnknownCorridor)?;
    let required_tier = thresholds.required_tier(amount);

    let now = env.ledger().timestamp();
    let day = storage::day_of(now);
    let spent = storage::daily_volume(env, sender, corridor_id, day);
    let headroom = spent.checked_add(amount).ok_or(ComplianceError::Overflow)?;
    if headroom > thresholds.daily_limit {
        return Err(ComplianceError::DailyLimitExceeded);
    }
    let remaining_daily = thresholds.daily_limit - headroom;

    let attestation = storage::get_attestation(env, sender);

    // A *revoked* attestation is a sanctions/fraud signal, so it blocks even a
    // transfer small enough that no verification would normally be required.
    // An absent or merely expired one does not: a first-time sender making a
    // small transfer is exactly who this network exists to serve.
    if let Some(record) = &attestation {
        if record.revoked {
            return Err(ComplianceError::AttestationRevoked);
        }
    }

    let held_tier = if required_tier == KycTier::None {
        attestation.as_ref().map_or(KycTier::None, |r| r.tier)
    } else {
        let record = attestation
            .as_ref()
            .ok_or(ComplianceError::AttestationMissing)?;
        if record.expires_at <= now {
            return Err(ComplianceError::AttestationExpired);
        }
        if !record.tier.satisfies(required_tier) {
            return Err(ComplianceError::TierTooLow);
        }
        record.tier
    };

    Ok(Evaluation {
        required_tier,
        held_tier,
        daily_total_after: headroom,
        remaining_daily,
    })
}

